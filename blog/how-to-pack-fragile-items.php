<h2>Glassware &amp; Stemware</h2>
<p>Wrap each piece individually in paper, then bubble wrap stems and rims. Stand glasses upright (never flat) in a box with a cushioned base, and fill gaps so nothing shifts.</p>

<h2>Plates &amp; Crockery</h2>
<p>Wrap plates individually and pack them <strong>on their edge, vertically</strong> like records — they resist pressure far better this way than stacked flat. Cushion the box top and bottom.</p>

<h2>Electronics &amp; TVs</h2>
<ul>
    <li>Use the original box if you still have it — it's purpose-built.</li>
    <li>Photograph cable connections before unplugging so reassembly is easy.</li>
    <li>Wrap screens in a soft cloth first, then bubble wrap, and mark "FRAGILE — THIS SIDE UP".</li>
    <li>Never lay a flat-screen TV flat; transport it upright.</li>
</ul>

<h2>Mirrors, Frames &amp; Glass Tops</h2>
<p>Tape an "X" across the glass to hold it if it cracks, wrap in bubble wrap and corner protectors, and carry on edge. Use a flat, mirror/picture box where possible.</p>

<h2>The Golden Rules</h2>
<ul>
    <li><strong>No empty space</strong> — gaps let items move and break. Fill with paper or foam.</li>
    <li><strong>Heavier items at the bottom</strong>, lighter and more delicate on top.</li>
    <li><strong>Don't overload</strong> a box; if it's too heavy it can burst.</li>
    <li><strong>Label clearly</strong> "FRAGILE" on all sides and which way is up.</li>
    <li>For very high-value items, ask about <a href="/contact-us.php">transit protection</a>.</li>
</ul>

