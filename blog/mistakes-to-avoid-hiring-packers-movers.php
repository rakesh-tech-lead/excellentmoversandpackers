<p>Last-minute bookings cost more and limit your choices. Book 1–2 weeks ahead (3–4 for big or inter-state moves).</p>

<h2>5. Ignoring an in-home/video survey</h2>
<p>A quote given without seeing your goods is a guess. Insist on a quick survey so the estimate — and the vehicle size — are accurate.</p>

<h2>6. Not decluttering first</h2>
<p>You pay to move volume. Sell or donate what you don't need before the survey to lower your bill.</p>

<h2>7. Forgetting about insurance/transit protection</h2>
<p>Ask what happens if something is damaged. For valuables, understand the protection options before you book.</p>

